"""Metadata forensics: EXIF, PNG text chunks, AI-generator signatures,
editing-software tags, ICC/XMP, and C2PA (Content Credentials) byte scan.

Principle: metadata is CONTEXT, not proof. Missing metadata is never treated
as evidence of AI generation; fabricated metadata is always possible.
"""
from __future__ import annotations

import io
from typing import Any, Dict

from PIL import Image
from PIL.ExifTags import TAGS

from .base import (AnalysisContext, AnalyzerResult, BaseAnalyzer, Evidence,
                   EvidenceDirection, SignalStatus, clamp)

AI_SIGNATURE_KEYWORDS = [
    "stable diffusion", "midjourney", "dall-e", "dalle", "firefly",
    "leonardo", "ideogram", "flux", "sdxl", "comfyui", "automatic1111",
    "novelai", "civitai", "dreamstudio", "nightcafe", "artbreeder",
    "runway", "pika", "luma", "synthetic", "ai generated", "generated by ai",
    "this image was generated", "diffusion", "invokeai", "fooocus",
    "seaart", "tensor.art",
]

EDITING_SOFTWARE_KEYWORDS = [
    "photoshop", "gimp", "lightroom", "snapseed", "picsart", "canva",
    "affinity", "paint.net", "paintshop", "pixelmator", "capture one",
    "dxo", "luminar", "vsco", "facetune", "afterlight", "polarr",
]

CAMERA_MAKERS = [
    "canon", "nikon", "sony", "fujifilm", "fuji", "panasonic", "olympus",
    "om system", "pentax", "ricoh", "leica", "hasselblad", "apple",
    "samsung", "google", "xiaomi", "huawei", "oneplus", "dji", "gopro",
]


def _clean(v: Any) -> str:
    if isinstance(v, bytes):
        try:
            return v.decode("utf-8", errors="ignore")
        except Exception:
            return ""
    return str(v)


def _contains(haystack: str, needles) -> str | None:
    low = haystack.lower()
    for n in needles:
        if n in low:
            return n
    return None


def _inspect_c2pa(blob: bytes, fmt: str):
    """Inspect Content Credentials. Returns (status, info).

    status: 'unvalidated' (manifest found, parsed heuristically - NOT
            signature-verified), 'invalid', 'missing', 'unsupported'.
    """
    fmt_u = (fmt or "").upper()
    if fmt_u in ("BMP", "GIF"):
        return "unsupported", {}
    head = blob[:600000]
    has_jumb = b"jumb" in head
    has_c2pa = b"c2pa" in head or b"c2pa_manifest" in head or b"c2pa_manifest_store" in head
    if not (has_jumb and has_c2pa):
        return "missing", {}
    info: dict = {}
    try:
        # Heuristic extraction of readable manifest strings near known markers.
        # JUMBF/CBOR is binary; we pull printable ASCII runs around markers.
        import re
        text = head.decode("utf-8", errors="ignore")
        # issuer / creator hints
        for pat, key in [
            (r'"issuer"\s*:\s*"([^"]{1,120})"', "issuer"),
            (r'dc:creator[^A-Za-z0-9]{1,40}([A-Za-z0-9 ._\-@]{2,60})', "creator_hint"),
            (r'claim_generator[^A-Za-z0-9]{1,40}([A-Za-z0-9 ._\-/]{2,80})', "claim_generator"),
            (r'"softwareAgent"\s*:\s*"([^"]{1,120})"', "software_agent"),
            (r'"name"\s*:\s*"([^"]{1,80})"\s*,\s*"version"\s*:\s*"([^"]{1,40})"', "generator"),
        ]:
            m = re.search(pat, text)
            if m:
                info[key] = " ".join(g for g in m.groups() if g).strip()[:120]
        # action history hints (c2pa actions like 'created', 'edited', 'generated')
        actions = sorted(set(re.findall(r'"action"\s*:\s*"([a-z_]{2,40})"', text)))
        if actions:
            info["actions"] = ", ".join(actions[:12])
        # AI-generation hints inside the manifest -> provenance evidence
        ai_markers = [s for s in ("ai_generated", "generative", "synthetic",
                                  "stable diffusion", "firefly", "midjourney", "dall")
                      if s in text.lower()]
        if ai_markers:
            info["ai_markers"] = ", ".join(sorted(set(ai_markers)))
        if not info:
            return "invalid", {"note": "JUMBF/C2PA markers found but no parseable manifest content"}
        return "unvalidated", info
    except Exception as exc:
        return "invalid", {"note": f"manifest parse failed: {type(exc).__name__}"}


class MetadataAnalyzer(BaseAnalyzer):
    name = "metadata"
    display_name = "Metadata Forensics"

    def analyze(self, ctx: AnalysisContext) -> AnalyzerResult:
        res = AnalyzerResult(
            name=self.name, display_name=self.display_name,
            ai_score=50.0, manip_score=50.0, confidence=70.0,
        )
        evidence: list[Evidence] = []
        warnings: list[str] = []
        technical: Dict[str, Any] = {}

        # --- re-open the ORIGINAL bytes to read container-level metadata ---
        try:
            raw = Image.open(io.BytesIO(ctx.file_bytes))
            raw.load()
        except Exception as exc:
            res.status = SignalStatus.UNABLE
            res.warnings.append(f"Could not re-open file for metadata scan: {exc}")
            res.confidence = 0
            return res

        technical["format"] = raw.format
        technical["mode"] = raw.mode
        technical["size"] = raw.size
        info = dict(raw.info or {})

        # PNG text chunks / generic info dict
        text_blobs: list[str] = []
        for k, v in info.items():
            if isinstance(v, (str, bytes)):
                text_blobs.append(f"{k}: {_clean(v)[:500]}")
            else:
                text_blobs.append(f"{k}: {str(v)[:200]}")
        technical["info_keys"] = sorted(str(k) for k in info.keys())

        # EXIF
        exif: Dict[str, Any] = {}
        try:
            raw_exif = raw.getexif()
            if raw_exif:
                for tag_id, val in raw_exif.items():
                    tag = TAGS.get(tag_id, str(tag_id))
                    if isinstance(val, bytes):
                        try:
                            val = val.decode("utf-8", errors="ignore")
                        except Exception:
                            val = f"<{len(val)} bytes>"
                    exif[str(tag)] = val
        except Exception:
            pass
        ctx.exif = exif
        technical["exif_tag_count"] = len(exif)
        interesting = {k: str(v)[:300] for k, v in exif.items()
                       if k in ("Make", "Model", "LensModel", "Software", "DateTime",
                                "DateTimeOriginal", "DateTimeDigitized", "ISOSpeedRatings",
                                "ExposureTime", "FNumber", "FocalLength", "GPSInfo",
                                "ImageDescription", "Artist", "Copyright", "ExifImageWidth",
                                "ExifImageHeight", "Orientation", "XPComment", "UserComment")}
        technical["exif_summary"] = interesting

        # ICC / XMP heuristics
        icc = raw.info.get("icc_profile") is not None
        xmp = any("xmp" in str(k).lower() or "xml" in str(k).lower() for k in info.keys())
        ctx.icc_present = icc
        ctx.xmp_present = xmp
        technical["icc_profile"] = icc
        technical["xmp"] = xmp

        # --- C2PA / Content Credentials (Phase 13) ---
        # States: VERIFIED | INVALID | MISSING | UNSUPPORTED.
        # Local analysis can only DETECT and PARSE manifest hints; cryptographic
        # VERIFIED status requires signature validation, which is out of scope -
        # so a found manifest is reported as UNVALIDATED (parsed, not verified).
        # MISSING is never AI evidence.
        c2pa_status, c2pa_info = _inspect_c2pa(ctx.file_bytes, fmt=(raw.format or ""))
        ctx.c2pa_present = c2pa_status in ("unvalidated", "invalid")
        ctx.c2pa_info = c2pa_info
        technical["c2pa_status"] = c2pa_status
        technical["c2pa_detected"] = ctx.c2pa_present
        technical["c2pa_info"] = c2pa_info
        if c2pa_status == "unvalidated":
            evidence.append(Evidence(
                "Content Credentials (C2PA) manifest detected (not cryptographically validated)",
                EvidenceDirection.NEUTRAL,
                "Manifest hints: " + "; ".join(
                    f"{k}={v}" for k, v in c2pa_info.items())[:300] +
                ". Provenance claims support context but were not signature-verified here.",
            ))
        elif c2pa_status == "invalid":
            evidence.append(Evidence(
                "C2PA data present but manifest appears malformed",
                EvidenceDirection.UNCERTAIN,
                "A damaged manifest cannot be trusted; treat provenance as unknown.",
            ))
        elif c2pa_status == "unsupported":
            technical["c2pa_note"] = "container format cannot carry C2PA"
        # MISSING: deliberately no evidence entry - absence proves nothing.

        # --- AI generator signatures ---
        all_text = " ".join(text_blobs) + " " + " ".join(f"{k} {v}" for k, v in exif.items())
        ai_hit = _contains(all_text, AI_SIGNATURE_KEYWORDS)
        ai_score, manip_score, confidence = 50.0, 50.0, 70.0

        if ai_hit:
            ai_score = 92.0
            confidence = 88.0
            evidence.append(Evidence(
                f"AI generator signature found in metadata: '{ai_hit}'",
                EvidenceDirection.SUPPORTS_AI,
                "A tag explicitly naming an AI generator is the strongest local metadata indicator. "
                "Tags can be forged, so this is strong but not absolute evidence.",
            ))
        else:
            evidence.append(Evidence(
                "No AI-generator signature found in metadata",
                EvidenceDirection.NEUTRAL,
                "Most AI generators strip or never embed signatures; absence proves nothing.",
            ))

        # --- Editing software ---
        software_fields = " ".join([
            str(exif.get("Software", "")), str(info.get("software", "")),
            *[v for k, v in info.items() if "soft" in str(k).lower() and isinstance(v, str)],
        ])
        edit_hit = _contains(software_fields + " " + all_text, EDITING_SOFTWARE_KEYWORDS)
        if edit_hit and not ai_hit:
            manip_score = max(manip_score, 78.0)
            evidence.append(Evidence(
                f"Editing software tag found: '{edit_hit}'",
                EvidenceDirection.SUPPORTS_MANIP,
                "The file claims it was processed by editing software. This indicates editing, "
                "not necessarily deceptive manipulation.",
            ))
        elif not edit_hit:
            evidence.append(Evidence(
                "No editing-software tag detected",
                EvidenceDirection.NEUTRAL,
                "Tags are easily removed; absence does not mean unedited.",
            ))

        # --- Camera provenance ---
        make = str(exif.get("Make", "")).lower()
        model = str(exif.get("Model", ""))
        cam_hit = _contains(make, CAMERA_MAKERS)
        has_capture_fields = any(k in exif for k in ("DateTimeOriginal", "ISOSpeedRatings",
                                                    "ExposureTime", "FNumber", "FocalLength"))
        if cam_hit and has_capture_fields:
            ai_score = min(ai_score, 30.0) if not ai_hit else ai_score
            evidence.append(Evidence(
                f"Camera capture metadata present ({exif.get('Make', '').strip()} {model.strip()})",
                EvidenceDirection.SUPPORTS_AUTHENTIC,
                "Complete capture metadata (make, model, exposure settings, timestamp) is "
                "consistent with a camera photograph. Metadata can be fabricated, so this is "
                "supporting context, not proof.",
            ))
            confidence = max(confidence, 78.0)
        elif cam_hit:
            evidence.append(Evidence(
                f"Camera make tag present ({exif.get('Make', '').strip()}) but capture details incomplete",
                EvidenceDirection.NEUTRAL,
                "Partial camera metadata; weaker provenance signal.",
            ))
        elif not exif and not text_blobs:
            warnings.append("No EXIF or embedded metadata found. Metadata can be removed or "
                            "altered and should not be considered definitive evidence.")
            evidence.append(Evidence(
                "Metadata absent",
                EvidenceDirection.UNCERTAIN,
                "Missing metadata is NOT evidence of AI generation. Screenshots, messaging apps "
                "and social platforms routinely strip metadata.",
            ))
            confidence = 45.0
        else:
            evidence.append(Evidence(
                "Some metadata present, but no camera capture fields",
                EvidenceDirection.NEUTRAL,
                "",
            ))

        # --- Timestamp sanity ---
        dt_orig = str(exif.get("DateTimeOriginal", "") or "")
        dt_mod = str(exif.get("DateTime", "") or "")
        if dt_orig and dt_mod and dt_orig != dt_mod:
            manip_score = max(manip_score, 62.0)
            evidence.append(Evidence(
                "Modification timestamp differs from capture timestamp",
                EvidenceDirection.SUPPORTS_MANIP,
                f"Captured: {dt_orig} | Modified: {dt_mod}. Suggests the file was re-saved after capture.",
            ))
            technical["timestamp_mismatch"] = True

        # --- GPS ---
        if "GPSInfo" in exif:
            evidence.append(Evidence("GPS location data present", EvidenceDirection.NEUTRAL,
                                     "Location tags support provenance context; they can be faked."))
            technical["gps_present"] = True

        # --- PNG A1111-style parameters chunk ---
        params = info.get("parameters") or ctx.png_text.get("parameters")
        if params and isinstance(params, str) and len(params) > 20:
            ai_score = 95.0
            confidence = 92.0
            evidence.append(Evidence(
                "Embedded generation parameters block found (PNG 'parameters' chunk)",
                EvidenceDirection.SUPPORTS_AI,
                "Typical of Stable Diffusion WebUI outputs; contains prompt/sampler/seed data.",
            ))
            technical["generation_parameters_present"] = True

        res.ai_score = clamp(ai_score)
        res.manip_score = clamp(manip_score)
        res.confidence = clamp(confidence)
        res.evidence = evidence
        res.warnings = warnings
        res.technical = technical
        if res.status == SignalStatus.OK and (not exif and not text_blobs):
            res.status = SignalStatus.WARNING
        return res
